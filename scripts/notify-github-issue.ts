import * as fs from 'fs';
import * as path from 'path';

interface AlertItem {
  id: string;
  company: string;
  careers_url: string;
  matching_text: string;
  job_url: string;
  detected_at: string;
  status: string;
}

interface ListingItem {
  id: string;
  company: string;
  title: string;
  location: string;
  apply_url: string;
  source_url: string;
  evidence?: {
    nigeria_eligible_phrase?: string;
    work_mode_phrase?: string;
    internship_phrase?: string;
    swe_phrase?: string;
  };
  eligibility: string;
  match_score?: number;
}

const DATA_DIR = path.join(process.cwd(), 'data');
const LISTINGS_FILE = path.join(DATA_DIR, 'listings.json');
const CHECK_ELIGIBILITY_FILE = path.join(DATA_DIR, 'check_eligibility.json');
const ALERTS_FILE = path.join(DATA_DIR, 'alerts.json');
const META_FILE = path.join(DATA_DIR, 'meta.json');

function loadJson<T>(filePath: string, fallback: T): T {
  try {
    if (fs.existsSync(filePath)) {
      return JSON.parse(fs.readFileSync(filePath, 'utf-8'));
    }
  } catch (err) {
    console.error(`Error loading ${filePath}:`, err);
  }
  return fallback;
}

export async function runGitHubIssueNotification() {
  console.log('========================================================================================');
  console.log('STEP D: GITHUB ACTIONS ISSUE NOTIFICATION SCRIPT');
  console.log('========================================================================================');

  const githubToken = process.env.GITHUB_TOKEN;
  const githubRepo = process.env.GITHUB_REPOSITORY; // e.g. "chiboy-star/Internship-Finder"

  const listings = loadJson<ListingItem[]>(LISTINGS_FILE, []);
  const checkEligibility = loadJson<ListingItem[]>(CHECK_ELIGIBILITY_FILE, []);
  const alerts = loadJson<AlertItem[]>(ALERTS_FILE, []);
  const meta = loadJson<any>(META_FILE, {});

  console.log(`- Loaded ${listings.length} verified listings`);
  console.log(`- Loaded ${checkEligibility.length} check_eligibility listings`);
  console.log(`- Loaded ${alerts.length} watcher alerts`);

  // Only proceed if there is something to report
  if (listings.length === 0 && checkEligibility.length === 0 && alerts.length === 0) {
    console.log('ℹ️ No new verified listings, check_eligibility roles, or watcher alerts. Skipping notification.');
    return;
  }

  // Format issue body / comment
  const timestamp = new Date().toISOString().replace('T', ' ').substring(0, 19) + ' UTC';
  let body = `## 🔔 New Internship Matches & Watcher Alerts Sync\n\n`;
  body += `**Sync Timestamp:** \`${timestamp}\`  \n`;
  body += `**Target Profile:** Chinemerem Madueke (3rd Year B.Sc. Software Engineering, Pan-Atlantic University)  \n`;
  body += `**Notification Channel:** Native GitHub Issue via built-in \`GITHUB_TOKEN\` (Email triggered automatically by GitHub)  \n\n`;

  body += `### 📊 Funnel & Alert Metrics\n\n`;
  body += `| Metric | Count | Details |\n`;
  body += `| :--- | :--- | :--- |\n`;
  body += `| **Verified Listings** | **${listings.length}** | Explicitly open to Nigeria / Africa |\n`;
  body += `| **Check Eligibility** | **${checkEligibility.length}** | Remote roles with unstated geographic bounds |\n`;
  body += `| **Watcher Keyword Alerts** | **${alerts.length}** | Detected on company career pages via polite DOM watcher |\n\n`;

  if (listings.length > 0) {
    body += `### 🎯 Verified Internship Matches (${listings.length})\n\n`;
    for (const item of listings) {
      body += `#### 🏢 ${item.company} — ${item.title}\n`;
      body += `- **Location:** ${item.location}\n`;
      body += `- **Apply URL:** [${item.apply_url}](${item.apply_url})\n`;
      if (item.evidence?.nigeria_eligible_phrase) {
        body += `- **Eligibility Quote:** *"${item.evidence.nigeria_eligible_phrase}"*\n`;
      }
      body += `\n`;
    }
  }

  if (alerts.length > 0) {
    body += `### 🚨 Careers-Page Watcher Alerts (${alerts.length})\n\n`;
    body += `The careers watcher detected active internship/trainee keywords on these watched company pages:\n\n`;
    for (const alert of alerts) {
      body += `- **${alert.company}**: [Careers Page](${alert.job_url || alert.careers_url})  \n`;
      body += `  > *"${alert.matching_text.replace(/\n+/g, ' ').trim()}"*  \n`;
    }
    body += `\n`;
  }

  if (checkEligibility.length > 0) {
    body += `### 🔍 Sample Check Eligibility Roles (${Math.min(checkEligibility.length, 5)} of ${checkEligibility.length})\n\n`;
    for (const item of checkEligibility.slice(0, 5)) {
      body += `- **${item.company}** — [${item.title}](${item.apply_url}) (${item.location})\n`;
    }
    body += `\n`;
  }

  body += `---\n*Automated notification generated by Internship-Finder daily pipeline. Zero paid services used.*`;

  const ISSUE_TITLE = 'New internship matches';

  if (!githubToken || !githubRepo) {
    console.log('\n⚠️ Notice: GITHUB_TOKEN or GITHUB_REPOSITORY not set (running locally).');
    console.log(`Would create/update GitHub Issue in repository: ${githubRepo || 'chiboy-star/Internship-Finder'}`);
    console.log(`Issue Title: "${ISSUE_TITLE}"`);
    console.log('\nSimulated Issue Content Preview:');
    console.log('----------------------------------------------------------------------------------------');
    console.log(body.substring(0, 800) + '...\n[Truncated for console]');
    console.log('----------------------------------------------------------------------------------------');
    console.log('Local dry-run completed successfully!');
    return;
  }

  const headers = {
    Authorization: `Bearer ${githubToken}`,
    Accept: 'application/vnd.github+json',
    'X-GitHub-Api-Version': '2022-11-28',
    'User-Agent': 'Internship-Finder-Polite-Notifier',
  };

  try {
    // 1. Search for existing open issue with title "New internship matches"
    const searchUrl = `https://api.github.com/repos/${githubRepo}/issues?state=open&per_page=50`;
    const searchRes = await fetch(searchUrl, { headers });

    if (!searchRes.ok) {
      const errText = await searchRes.text();
      throw new Error(`Failed to list issues: ${searchRes.status} ${errText}`);
    }

    const issues = (await searchRes.json()) as Array<{ id: number; number: number; title: string }>;
    const existingIssue = issues.find((i) => i.title.trim().toLowerCase() === ISSUE_TITLE.toLowerCase());

    if (existingIssue) {
      console.log(`Found existing open issue #${existingIssue.number}: "${existingIssue.title}".`);
      console.log(`Posting update comment to issue #${existingIssue.number}...`);

      const commentUrl = `https://api.github.com/repos/${githubRepo}/issues/${existingIssue.number}/comments`;
      const commentRes = await fetch(commentUrl, {
        method: 'POST',
        headers: {
          ...headers,
          'Content-Type': 'application/json',
        },
        body: JSON.stringify({ body }),
      });

      if (!commentRes.ok) {
        const errText = await commentRes.text();
        throw new Error(`Failed to post comment: ${commentRes.status} ${errText}`);
      }

      console.log(`✅ Successfully posted update comment to GitHub Issue #${existingIssue.number}!`);
    } else {
      console.log(`No open issue titled "${ISSUE_TITLE}" found. Creating a new issue...`);

      const createUrl = `https://api.github.com/repos/${githubRepo}/issues`;
      const createRes = await fetch(createUrl, {
        method: 'POST',
        headers: {
          ...headers,
          'Content-Type': 'application/json',
        },
        body: JSON.stringify({
          title: ISSUE_TITLE,
          body,
          labels: ['internship-alerts', 'automated-sync'],
        }),
      });

      if (!createRes.ok) {
        const errText = await createRes.text();
        throw new Error(`Failed to create issue: ${createRes.status} ${errText}`);
      }

      const created = (await createRes.json()) as { number: number; html_url: string };
      console.log(`✅ Successfully created GitHub Issue #${created.number}: ${created.html_url}`);
    }
  } catch (err: any) {
    console.error('Error in GitHub Issue notification:', err.message);
    throw err;
  }
}

if (require.main === module) {
  runGitHubIssueNotification().catch((err) => {
    console.error(err);
    process.exit(1);
  });
}

